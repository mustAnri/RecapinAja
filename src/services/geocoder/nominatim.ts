/**
 * Formats an address from Nominatim response into Indonesian style.
 * 
 * The format follows: Jalan + Kec + Kab + Prov pattern commonly used in Indonesia.
 * - Jalan: Street/road name
 * - Kec: Kecamatan (district)
 * - Kab: Kabupaten (regency/city)
 * - Prov: Provinsi (province/state)
 * 
 * Example: "Jl. Sudirman, Kec. Menteng, Jakarta Pusat, DKI Jakarta"
 * 
 * @param response - Nominatim reverse geocoding response
 * @returns Formatted Indonesian-style address string
 */
export function formatIndonesianAddress(response: NominatimReverseResponse): string {
  const { address } = response;
  const parts: string[] = [];

  // 1. Street/Road component
  if (address.road) {
    // Convert common street abbreviations
    let street = address.road.trim();
    
    // Normalize common prefixes
    street = street.replace(/^Jalan\s+/i, '');
    street = street.replace(/^Jl\./i, 'Jl.');
    
    if (!/^Jl\.|^Jalan\b/i.test(street)) {
      street = 'Jl. ' + street;
    }
    
    parts.push(street);
  } else if (address.neighbourhood) {
    parts.push(address.neighbourhood);
  }

  // 2. District/Kecamatan component
  if (address.suburb || address.quarter) {
    const district = address.suburb || address.quarter;
    parts.push(`Kec. ${district}`);
  }

  // 3. City/Regency/Kabupaten component
  if (address.city || address.county) {
    const cityComponent = address.city ?? address.county;
    
    // Type guard to ensure cityComponent is a valid string
    if (!cityComponent) {
      return response.display_name;
    }
    
    // Check if this is a regency (kabupaten) or city (kota)
    let cityText = cityComponent;
    
    // Common regency indicators in Indonesia
    const kabupatenPatterns = [
      /kabupaten/i,
      /regensi/i,
      /\b(kota|kotamadya)\b/i
    ];
    
    for (const pattern of kabupatenPatterns) {
      if (pattern.test(cityComponent)) {
        cityText = cityComponent.replace(pattern, '').trim();
        break;
      }
    }
    
    if (cityText && cityText.length > 0) {
      parts.push(`Kab. ${cityText}`);
    }
  }

  // 4. Province/Provinsi component
  if (address.state || address.region) {
    const province = address.state ?? address.region;
    if (province && province !== 'Indonesia') {
      // Add province prefix for clarity
      parts.push(`Prov. ${province}`);
    }
  }

  // 5. Optional: Postcode
  if (address.postcode) {
    parts.push(`Pos: ${address.postcode}`);
  }

  // Join all components with comma separator
  return parts.length > 0 ? parts.join(', ') : response.display_name;
}

/**
 * Performs reverse geocoding - converts latitude/longitude to address.
 * 
 * Given coordinates, retrieves the human-readable address from Nominatim API
 * and returns it formatted according to Indonesian addressing conventions.
 * 
 * @param lat - Latitude in decimal degrees (-90 to 90)
 * @param lon - Longitude in decimal degrees (-180 to 180)
 * @param options - Optional configuration settings
 * @returns Promise resolving to formatted Indonesian address string
 * @throws GeocodingError if coordinates are invalid or API request fails
 * 
 * @example
 * ```typescript
 * const address = await reverseGeocode(-6.2088, 106.8456);
 * // Returns: "Jl. Medan Merdeka Selatan, Kec. Gambir, Jakarta Pusat, DKI Jakarta"
 * ```
 */
export async function reverseGeocodeStructured(
  lat: number,
  lon: number,
  options: ReverseGeocodeOptions = {}
): Promise<NominatimReverseResponse> {
  const { timeout = DEFAULT_TIMEOUT_MS } = options;

  try {
    // Validate coordinates
    validateCoordinates(lat, lon);

    // Create abort controller with timeout
    const controller = createTimeoutController(timeout);

    // Build query parameters
    const params = new URLSearchParams({
      lat: lat.toFixed(6),
      lon: lon.toFixed(6),
      format: 'json',
      addressdetails: '1',
      'namedetails': '1',
    });

    // Add optional parameters
    if (options.extratags) {
      params.set('extratags', '1');
    }

    if (options.acceptLanguage) {
      params.set('acceptlanguage', options.acceptLanguage);
    }

    // Make API request
    const url = `${NOMINATIM_BASE_URL}/reverse?${params.toString()}`;

    const response = await fetch(url, {
      method: 'GET',
      headers: DEFAULT_HEADERS,
      signal: controller.signal,
    });

    // Clear timeout on success
    controller.clearRequest();

    // Parse and return the structured response
    return await parseJsonResponse<NominatimReverseResponse>(response);

  } catch (error: unknown) {
    // Re-throw known errors, wrap others
    if (error instanceof NominatimGeocodingError) {
      throw error;
    }

    throw new NominatimGeocodingError(
      `Reverse geocoding failed: ${error instanceof Error ? error.message : 'Unknown error'}`,
      error,
      'REVERSE_GEOCODING_FAILED'
    );
  }
}

export async function reverseGeocode(
  lat: number,
  lon: number,
  options: ReverseGeocodeOptions = {}
): Promise<string> {
  const apiResponse = await reverseGeocodeStructured(lat, lon, options);
  return formatIndonesianAddress(apiResponse);
}

/**
 * Performs forward geocoding - searches for places by name/description.
 * 
 * Searches the Nominatim database for locations matching the given query,
 * such as area names, streets, cities, or landmarks. Returns the top result
 * if a match is found.
 * 
 * @param query - Search query (area name, street, city, landmark, etc.)
 * @param options - Query configuration options (optional parameters)
 * @returns Promise resolving to the best matching NominatimForwardResponse
 * @throws GeocodingError if query is empty, no results found, or API request fails
 * 
 * @example
 * ```typescript
 * const result = await forwardGeocode('Monas, Jakarta');
 * // Returns: { lat: "-6.175392", lon: "106.827153", ... }
 * ```
 */
export async function forwardGeocode(
  query: string,
  options?: ForwardGeocodeOptions
): Promise<NominatimForwardResponse> {
  const limit = options?.limit ?? DEFAULT_LIMIT;
  const countrycodes = options?.countrycodes ?? 'id'; // Default to Indonesia for better accuracy

  try {
    // Validate query
    if (!query || typeof query !== 'string' || query.trim().length === 0) {
      throw new NominatimGeocodingError(
        'Search query cannot be empty',
        undefined,
        'EMPTY_QUERY'
      );
    }

    const trimmedQuery = query.trim();

    // Create abort controller with timeout
    const controller = createTimeoutController(DEFAULT_TIMEOUT_MS);

    // Build query parameters
    const params = new URLSearchParams({
      q: trimmedQuery,
      format: 'json',
      addressdetails: '1',
      limit: limit.toString(),
    });

    // Add country code restriction if provided
    if (countrycodes) {
      params.set('countrycodes', countrycodes);
    }

    // Make API request
    const url = `${NOMINATIM_BASE_URL}/search?${params.toString()}`;

    const headers: Record<string, string> = {
      ...DEFAULT_HEADERS,
    };

    if (options?.userAgent) {
      headers['User-Agent'] = options.userAgent;
    }

    const response = await fetch(url, {
      method: 'GET',
      headers,
      signal: controller.signal,
    });

    // Clear timeout on success
    controller.clearRequest();

    // Handle non-OK responses
    if (!response.ok) {
      if (response.status === 429) {
        throw new NominatimGeocodingError(
          'Rate limit exceeded. Please slow down your requests.',
          { status: response.status },
          'RATE_LIMIT_EXCEEDED'
        );
      }

      let errorMessage = `HTTP ${response.status}`;
      try {
        const errorData = await response.text();
        errorMessage = errorData || errorMessage;
      } catch {
        // Ignore parsing errors
      }

      throw new NominatimGeocodingError(
        `Forward geocoding failed: ${errorMessage}`,
        { status: response.status },
        'FORWARD_GEOCODING_FAILED'
      );
    }

    // Parse response array
    let results: NominatimForwardResponse[];
    try {
      results = await response.json() as NominatimForwardResponse[];
    } catch (error: unknown) {
      throw new NominatimGeocodingError(
        `Failed to parse API response: ${error instanceof Error ? error.message : 'Unknown error'}`,
        error,
        'PARSE_ERROR'
      );
    }

    // Validate results
    if (results.length === 0) {
      throw new NominatimGeocodingError(
        `No results found for query: "${trimmedQuery}"`,
        { query: trimmedQuery },
        'NO_RESULTS_FOUND'
      );
    }

    // Filter results by importance score (confidence threshold)
    const qualifiedResults = results.filter(result => 
      result.importance >= MIN_IMPORTANCE_SCORE
    );

    if (qualifiedResults.length === 0) {
      throw new NominatimGeocodingError(
        `No suitable results found for query: "${trimmedQuery}". Results had low confidence scores.`,
        { query: trimmedQuery },
        'LOW_CONFIDENCE'
      );
    }

    // Sort by importance and return best match
    const bestMatch = qualifiedResults.sort((a, b) => b.importance - a.importance)[0];

    if (!bestMatch.lat || !bestMatch.lon) {
      throw new NominatimGeocodingError(
        'Location has no valid coordinates',
        bestMatch,
        'INVALID_COORDINATES'
      );
    }

    return bestMatch;

  } catch (error: unknown) {
    // Re-throw known errors, wrap others
    if (error instanceof NominatimGeocodingError) {
      throw error;
    }

    throw new NominatimGeocodingError(
      `Forward geocoding failed: ${error instanceof Error ? error.message : 'Unknown error'}`,
      error,
      'FORWARD_GEOCODING_ERROR'
    );
  }
}

/**
 * Convenience wrapper for searching by area name with default Indonesian bounds.
 * Simplifies forward geocoding for Indonesian locations.
 * 
 * @param areaName - Name of the area, district, city, or landmark
 * @param limit - Maximum number of results to consider (default: 3)
 * @returns Promise resolving to the best matching location
 */
export async function searchByAreaName(
  areaName: string,
  limit?: number
): Promise<NominatimForwardResponse> {
  const config: ForwardGeocodeOptions = {
    countrycodes: 'id',
  };
  
  if (limit !== undefined) {
    config.limit = limit;
  }
  
  return forwardGeocode(areaName, config);
}

/**
 * Checks if a location string might represent a valid address or place name.
 * Used to determine whether geocoding is necessary before attempting a call.
 * 
 * @param text - Text to validate
 * @returns True if the text appears to be a valid geocoding candidate
 */
export function isValidGeocodeQuery(text: string): boolean {
  if (!text || typeof text !== 'string') {
    return false;
  }

  const cleaned = text.trim();
  return cleaned.length >= 2 && cleaned.length <= 500;
}

/**
 * Converts decimal degrees to degrees-minutes-seconds (DMS) format.
 * Useful for displaying coordinates in traditional formats.
 * 
 * @param decimal - Coordinate in decimal degrees
 * @returns Object with degrees, minutes, seconds, and direction
 */
export function toDMS(decimal: number): {
  d: number;
  m: number;
  s: number;
  dir: string;
} {
  const isNegative = decimal < 0;
  const absDecimal = Math.abs(decimal);

  const d = Math.floor(absDecimal);
  const mDec = (absDecimal - d) * 60;
  const m = Math.floor(mDec);
  const s = ((mDec - m) * 60).toFixed(2);

  return {
    d,
    m,
    s: parseFloat(s.toString()),
    dir: isNegative ? (isNaN(decimal) ? '' : (Math.abs(decimal) > 90 ? 'S' : 'W')) : (Math.abs(decimal) > 90 ? 'N' : 'E'),
  };
}
