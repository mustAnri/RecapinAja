/**
 * Address components returned by Nominatim reverse geocoding.
 * Contains structured address parts that can be used to build custom formats.
 */
export interface NominatimAddressComponents {
  /** House number */
  house_number?: string;
  /** Road/street name */
  road?: string;
  /** Suburb/neighbourhood */
  neighbourhood?: string;
  /** Quarter/district */
  quarter?: string;
  /** City/district level 3 */
  city_district?: string;
  /** City/town/village */
  city?: string;
  /** Town */
  town?: string;
  /** Village */
  village?: string;
  /** Suburbs at level 4 */
  suburb?: string;
  /** State/province */
  state?: string;
  /** Country code (ISO 3166-1 alpha-2) */
  country_code?: string;
  /** Country name */
  country?: string;
  /** Postcode */
  postcode?: string;
  /** County */
  county?: string;
  /** Region */
  region?: string;
}

/**
 * Response structure from Nominatim reverse geocoding endpoint.
 * Contains the full address details for a specific latitude/longitude.
 */
export interface NominatimReverseResponse {
  /** Place ID uniquely identifying this location */
  place_id: number;
  /** Licence information */
  licence: string;
  /** OSM node ID if available */
  osm_type?: string;
  /** OSM relation ID if available */
  osm_id?: number;
  /** Latitude (decimal degrees) */
  lat: string;
  /** Longitude (decimal degrees) */
  lon: string;
  /** Display name as generated by Nominatim */
  display_name: string;
  /** Address object with structured components */
  address: NominatimAddressComponents;
  /** Bounding box of the place */
  boundingbox: [string, string, string, string];
  /** Type of feature (e.g., "house", "road", "city") */
  type: string;
  /** Place rank (importance indicator) */
  place_rank: number;
  /** Category type (e.g., "building", "highway") */
  category_type?: string;
  /** Whether this item is a valid address */
  named: boolean;
}

