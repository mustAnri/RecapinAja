/**
 * Validates coordinate inputs for reverse geocoding.
 * Throws GeocodingError if coordinates are invalid.
 * 
 * @param lat - Latitude in decimal degrees (-90 to 90)
 * @param lon - Longitude in decimal degrees (-180 to 180)
 */
function validateCoordinates(lat: number, lon: number): void {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) {
    throw new NominatimGeocodingError(
      'Latitude and longitude must be finite numbers',
      undefined,
      'INVALID_COORDINATES'
    );
  }

  if (lat < -90 || lat > 90) {
    throw new NominatimGeocodingError(
      `Invalid latitude: ${lat}. Must be between -90 and 90`,
      { lat },
      'INVALID_LATITUDE'
    );
  }

  if (lon < -180 || lon > 180) {
    throw new NominatimGeocodingError(
      `Invalid longitude: ${lon}. Must be between -180 and 180`,
      { lon },
      'INVALID_LONGITUDE'
    );
  }
}

/**
 * Creates a fetch controller with timeout capability.
 * 
 * @param timeoutMs - Timeout in milliseconds
 * @returns Object with signal and cleanup method
 */
function createTimeoutController(timeoutMs: number): {
  signal: AbortSignal;
  clearRequest: () => void;
} {
  const controller = new AbortController();
  let timeoutId: ReturnType<typeof setTimeout> | null = setTimeout(() => controller.abort(), timeoutMs);
  
  // Clean up timeout on successful completion
  return {
    signal: controller.signal,
    clearRequest: () => {
      if (timeoutId) {
        clearTimeout(timeoutId);
        timeoutId = null;
      }
    },
  };
}

/**
 * Parses JSON response with error handling.
 * 
 * @param response - Fetch response object
 * @returns Parsed JSON data
 */
async function parseJsonResponse<T>(response: Response): Promise<T> {
  if (!response.ok) {
    let errorMessage = `HTTP ${response.status}`;
    
    try {
      const errorData = await response.text();
      errorMessage = errorData || errorMessage;
    } catch {
      // Ignore parsing errors, use status code message
    }

    throw new NominatimGeocodingError(
      `Geocoding API request failed: ${errorMessage}`,
      { status: response.status },
      'API_REQUEST_FAILED'
    );
  }

  try {
    return await response.json() as T;
  } catch (error: unknown) {
    throw new NominatimGeocodingError(
      `Failed to parse API response: ${error instanceof Error ? error.message : 'Unknown error'}`,
      error,
      'PARSE_ERROR'
    );
  }
}

