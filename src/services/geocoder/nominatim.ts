/** Base URL for Nominatim API */
const NOMINATIM_BASE_URL = 'https://nominatim.openstreetmap.org';

/** Default timeout for API requests (in milliseconds) */
const DEFAULT_TIMEOUT_MS = 10000;

/** Default request timeout headers */
const DEFAULT_HEADERS = {
  'Accept': 'application/json',
  'User-Agent': 'RecapTestDrive/1.0 (geocoding service)',
};

/** Maximum results for forward geocoding */
const DEFAULT_LIMIT = 5;

/** Minimum confidence score for valid results */
const MIN_IMPORTANCE_SCORE = 0.1;

