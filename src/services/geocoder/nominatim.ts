/**
 * Nominatim OpenStreetMap Geocoding Service
 * 
 * Provides forward and reverse geocoding capabilities using the Nominatim API.
 * Forward geocoding converts area names to coordinates.
 * Reverse geocoding converts coordinates to addresses in Indonesian format.
 * 
 * @see https://nominatim.org/release-docs/latest/api/
 */

// ============================================================================
// Custom Error Class
// ============================================================================

/**
 * Custom error class for Nominatim geocoding-related failures.
 * Wraps errors from network requests, parsing failures, or API errors.
 */
export class NominatimGeocodingError extends Error {
  /** Additional context about where/why the error occurred */
  public readonly code?: string;

  constructor(
    message: string,
    cause?: unknown,
    code?: string
  ) {
    super(message);
    this.name = 'NominatimGeocodingError';
    this.cause = cause;
    this.code = code;

    // Set prototype chain properly
    Object.setPrototypeOf(this, NominatimGeocodingError.prototype);
  }
}

